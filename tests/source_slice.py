"""소스 텍스트 단정문용 슬라이스 헬퍼.

이 저장소의 프론트엔드 안전망은 거의 전부 "파일을 문자열로 읽어 부분 문자열을
검사"하는 형태다. 그때 `text.split(start)[1]` 로 자르면 조각이 **EOF 까지 흘러**
뒤쪽의 무관한 함수 정의·상수를 삼킨다. 그러면 단정문이 이름과 다른 이유로 통과하고,
막으려던 회귀를 영원히 못 잡는다 — 2026-09-09 감사에서 5건 확인됐고 그중 하나는
변이 검증으로 "고쳐야 할 코드를 지워도 그린"임이 증명됐다.

강제 장치는 두지 않는다. 새로 쓰거나 손대는 단정문만 이걸 쓴다.
"""


def slice_between(text: str, start: str, end: str) -> str:
    """`start` 다음부터 `end` 앞까지를 돌려준다. **양쪽 경계를 모두 요구한다.**

    경계를 못 찾으면 조용히 넓어지는 대신 즉시 실패한다 — 슬라이스가 의도보다
    넓어지는 건 테스트가 거짓말을 시작하는 지점이라 침묵시키면 안 된다.
    """
    _, found, rest = text.partition(start)
    assert found, f"시작 경계를 찾지 못했다: {start!r}"
    body, found, _ = rest.partition(end)
    assert found, f"끝 경계를 찾지 못했다: {end!r} (시작 {start!r} 이후)"
    return body
